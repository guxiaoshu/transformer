"""
================================================================================
Transformer 教育版 — 全局配置文件
================================================================================

【什么是 Config】
  把所有可调参数集中在一个地方。
  好处：
    1. 改一个值，所有引用的地方自动生效
    2. 不想到处找"这个数字是什么意思"
    3. 便于做实验：复制一份改几个参数，对比效果

【使用方法】
  from config import config
  print(config.d_model)  # → 256
  config.batch_size = 32  # 运行时修改

================================================================================
"""

from dataclasses import dataclass
import torch
import os


@dataclass
class EduConfig:
    """教育版配置 — 小模型、快速训练、吃透每个细节"""

    # ==========================================================================
    # 路径配置
    # ==========================================================================
    # 数据目录：OPUS-100 数据集的 Arrow 文件位置
    # └─ en-zh/0.0.0/{hash}/opus-100-train.arrow
    data_dir: str = "D:/Codefield/Transformer/huggingface/datasets/Helsinki-NLP___opus-100"

    # 保存目录：模型检查点、词表文件存放位置
    save_dir: str = os.path.join(os.path.dirname(__file__), "checkpoints")

    # 词表保存路径：训练后保存，推理时加载
    tokenizer_path: str = os.path.join(os.path.dirname(__file__), "checkpoints", "tokenizer.json")

    # ==========================================================================
    # 语言方向
    # ==========================================================================
    # 源语言 = 中文 (zh)，目标语言 = 英文 (en)
    # OPUS-100 存储格式是 en→zh，但我们训练方向是 zh→en，所以加载时交换
    src_lang: str = "zh"
    tgt_lang: str = "en"

    # ==========================================================================
    # 数据配置
    # ==========================================================================
    # 训练样本数：教育版只用5万条（全量100万的5%）
    # 为什么只取5万？教育版目标是快速迭代看效果
    max_train_samples: int = 50000

    # 最大序列长度：token数（含SOS/EOS）
    # 64意味着句子最多62个有效token
    # 设置太大会浪费显存，太小会截断长句
    max_seq_len: int = 64

    # 最小序列长度：过滤掉只有1个token的句子（信息量太少）
    min_seq_len: int = 2

    # ==========================================================================
    # 词表配置
    # ==========================================================================
    # 联合词表大小（包含4个特殊token + 中文字符 + 英文单词）
    # 10000 = 4特殊 + ~4998中文 + ~4998英文
    vocab_size: int = 10000

    # ==========================================================================
    # 模型架构配置
    # ==========================================================================
    # 隐藏维度：token嵌入后的向量维度
    # 256 = 相对较小的模型（生产版用512）
    # 越大→表达能力越强→更慢且更占显存
    d_model: int = 256

    # 注意力头数：把 d_model 拆成 n_heads 份，每份独立做注意力
    # 8个头 × 32维/头 = 256维
    # 必须满足 d_model % n_heads == 0
    n_heads: int = 8

    # 编码器层数：对源语言做多少层Self-Attention
    # 3层 = 浅层网络（生产版用6层）
    n_encoder_layers: int = 3

    # 解码器层数：生成目标语言时做多少层Self/Cross-Attention
    n_decoder_layers: int = 3

    # FFN隐藏层维度：注意力后的前馈网络中间维度
    # 512 = 2倍 d_model（标准用4倍=1024，这里取2倍加速训练）
    d_ff: int = 512

    # Dropout比例：随机丢弃10%的神经元
    # 只在训练时生效，推理时自动关闭
    # 0.1 = 标准值（太大→欠拟合，太小→过拟合）
    dropout: float = 0.1

    # ==========================================================================
    # Norm 模式：Post-Norm vs Pre-Norm
    # ==========================================================================
    # "post": 原论文结构 → x = Norm(x + Sublayer(x))
    #         历史原因，大多数经典实现用这个
    # "pre":  现代结构 → x = x + Sublayer(Norm(x))
    #         训练更稳定，GPT/Llama 等都用 Pre-Norm
    norm_mode: str = "post"

    # ==========================================================================
    # 推理配置
    # ==========================================================================
    # Beam Search 束宽：推理时保留的候选路径数
    # 1 = 贪心解码（最快），4 = 标准束搜索（质量/速度平衡）
    beam_size: int = 4

    # 位置编码最大长度：预计算前max_pos_len个位置的编码向量
    # 应该 ≥ max_seq_len
    max_pos_len: int = 64

    # ==========================================================================
    # 训练配置
    # ==========================================================================
    # 批次大小：每个step用多少条数据算一次梯度
    # 64 = 适合教育版（小模型+短序列+8GB显存）
    batch_size: int = 64

    # 训练轮数：完整遍历训练集30次
    epochs: int = 30

    # 初始学习率：控制参数更新的步长
    # 1e-4 = 0.0001，Transformer的典型起始值
    lr: float = 1e-4

    # 预热步数：前2000步线性增长学习率
    # ≈ 3个epoch (2000/710≈2.8)
    warmup_steps: int = 2000

    # 梯度裁剪阈值：限制梯度L2范数不超过1.0
    # 防止某个batch梯度爆炸导致训练崩溃
    grad_clip: float = 1.0

    # 标签平滑系数：10%的概率均匀分配给非正确答案
    # 0 = 标准Cross-Entropy，0.1 = 标准平滑值
    label_smoothing: float = 0.1

    # ==========================================================================
    # AdamW 优化器配置
    # ==========================================================================
    # β1: 一阶动量系数（控制"惯性"）
    # 0.9 = 标准值
    adam_beta1: float = 0.9

    # β2: 二阶动量系数（控制"学习率自适应"）
    # 0.98 = Transformer常用值（比通常的0.999更低，更"健忘"）
    adam_beta2: float = 0.98

    # ε: 防止除零的小常数
    adam_eps: float = 1e-9

    # 权重衰减系数：L2正则化的强度
    # 0.01 = 适度正则化，防止过拟合
    weight_decay: float = 0.01

    # ==========================================================================
    # 设备
    # ==========================================================================
    # 自动检测：有CUDA用GPU，没有用CPU
    device: str = "cuda" if torch.cuda.is_available() else "cpu"

    # ==========================================================================
    # 日志与保存
    # ==========================================================================
    # 每N个batch打印一次日志
    log_interval: int = 50

    # 是否在模型前向传播时打印形状信息（学习用）
    # True = 训练和推理时都会打印每步的维度变化
    verbose: bool = True

    # 是否保存在验证集上表现最好的模型
    save_best: bool = True


# 全局配置实例 — 所有模块通过 from config import config 引用
config = EduConfig()
